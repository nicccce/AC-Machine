class OrderedStream {
public:
    int n, ptr;
    vector<string> data;
    OrderedStream(int n) : n(n), ptr(1), data(n + 1) {}
    
    vector<string> insert(int idKey, string value) {
        data[idKey] = value;
        vector<string> res;
        if (idKey != ptr) return res;
        while (ptr <= n && !data[ptr].empty()) {
            res.push_back(data[ptr++]);
        }
        return res;
    }
};

