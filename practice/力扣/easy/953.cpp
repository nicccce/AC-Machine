class Solution {
public:
    bool isAlienSorted(vector<string>& words, string order) {
        vector<int> ord(26);
        for (int i = 0; i < 26; i++) {
            ord[order[i] - 'a'] = i;
        }
        
        auto cmp = [&](const string &a, const string &b) {
            int n = a.length();
            int m = b.length();
            int i = 0;
            while (i < n && i < m) {
                if (ord[a[i] - 'a'] < ord[b[i] - 'a']) {
                    return true;
                } else if (ord[a[i] - 'a'] > ord[b[i] - 'a']) {
                    return false;
                }
                i++;
            }
            return i == n;
        };
        
        for (int i = 0; i < words.size() - 1; i++) {
            if (!cmp(words[i], words[i + 1])) {
                return false;
            }
        }
        
        return true;
    }
};