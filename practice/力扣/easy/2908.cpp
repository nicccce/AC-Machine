/*
 * [2908] 元素和最小的山形三元组 I
 */

class Solution {
public:
    int minimumSum(vector<int>& nums) {
        int n = nums.size();
        int result = INT_MAX;
        
        for (int i = 0; i < n; i++) {
            for (int j = i + 1; j < n; j++) {
                for (int k = j + 1; k < n; k++) {
                    if (nums[i] < nums[j] && nums[k] < nums[j]) {
                        result = min(result, nums[i] + nums[j] + nums[k]);
                    }
                }
            }
        }
        
        return result == INT_MAX ? -1 : result;
    }
};