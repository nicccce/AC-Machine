/*
 * [441] 排列硬币
 */

class Solution {
public:
    int arrangeCoins(int n) {
        long long left = 1, right = n;
        while (left <= right) {
            long long mid = left + (right - left) / 2;
            long long total = mid * (mid + 1) / 2; // 前mid行需要的硬币总数
            if (total == n) {
                return mid;
            } else if (total < n) {
                left = mid + 1;
            } else {
                right = mid - 1;
            }
        }
        return right; // 返回能构成完整阶梯的最大行数
    }
};