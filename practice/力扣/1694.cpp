// @lc code=start
class Solution {
public:
    string reformatNumber(string number) {
        string digits;
        for (char c : number) {
            if (c != ' ' && c != '-') {
                digits += c;
            }
        }
        
        string result;
        int n = digits.length();
        int i = 0;
        
        while (n > 0) {
            if (n > 4) {
                result += digits.substr(i, 3);
                i += 3;
                n -= 3;
                if (n > 0) result += "-";
            } else {
                if (n == 4) {
                    result += digits.substr(i, 2);
                    result += "-";
                    result += digits.substr(i + 2, 2);
                    n = 0;
                } else {
                    result += digits.substr(i, n);
                    n = 0;
                }
            }
        }
        
        return result;
    }
};
