#include<bits/stdc++.h>
using namespace std;
typedef long long ll;
#define int long long
const int mod = 1e9 + 7;
const int mod_exp = 1e9 + 6;

int C[1005][1005];

// 用杨辉三角预处理组合数，对 1e9+6 取模
void init_C() {
    for (int i = 0; i <= 1002; i++) {
        C[i][0] = 1;
        for (int j = 1; j <= i; j++) {
            C[i][j] = (C[i - 1][j - 1] + C[i - 1][j]) % mod_exp;
        }
    }
}

int qpow(int a, int b) {
    a %= mod;
    int res = 1LL;
    while (b) {
        if (b & 1LL)
            res = res * a % mod;
        a = a * a % mod;
        b >>= 1LL;
    }
    return res % mod;
}

signed main() {
    ios::sync_with_stdio(0);
    cin.tie(0), cout.tie(0);
    
    // 初始化组合数表
    init_C(); 

    auto solve = [&]() {
        int n, m;
        if (!(cin >> n >> m)) return;
        vector<int> a(n + 1), prefix(n + 1, 0);
        for(int i = 1; i <= n; i++){
            cin >> a[i];
            prefix[i] = prefix[i - 1] + a[i];
        }
        
        // 核心修正：处理特判 m = 1 的情况
        if (m == 1) {
            cout << prefix[n] % mod << "\n";
            return;
        }

        int ans = 1;
        
        // 1. 前缀情况 prefix[1...j]
        for(int j = 1; j <= n - 1; j++){
            int N = n - j - 1;
            int K = m - 2;
            if(N >= K && K >= 0) {
                int val = prefix[j] % mod;
                if (val == 0) { cout << 0 << "\n"; return; } // 防 0^0 错判
                ans = (ans * qpow(val, C[N][K])) % mod;
            }
        }
        
        // 2. 后缀情况 prefix[i+1...n]
        for(int i = 1; i <= n - 1; i++){
            int N = i - 1;
            int K = m - 2;
            if(N >= K && K >= 0) {
                int val = (prefix[n] - prefix[i]) % mod;
                if (val == 0) { cout << 0 << "\n"; return; }
                ans = (ans * qpow(val, C[N][K])) % mod;
            }
        }
        
        // 3. 中间段情况 prefix[i+1...j]
        for(int i = 1; i <= n - 1; i++){
            for(int j = i + 1; j <= n - 1; j++){
                int N = n - j + i - 2;
                int K = m - 3;
                if(N >= K && K >= 0) {
                    int val = (prefix[j] - prefix[i]) % mod;
                    if (val == 0) { cout << 0 << "\n"; return; }
                    ans = (ans * qpow(val, C[N][K])) % mod;
                }
            }
        }
        
        cout << ans << "\n";
    };

    solve();
    return 0;
}

