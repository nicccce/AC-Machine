#include<bits/stdc++.h>
using namespace std;
#define int long long
const int inf=0x3f3f3f3f;
struct Point {
    int x, y;
};
signed main() {
    ios::sync_with_stdio(0);
    cin.tie(0),cout.tie(0);
    auto solve = [&]() {
        int n, m, k, r;
        cin >> n >> m >> k >> r;

        int total_nodes = n + m;
        vector<Point> nodes(total_nodes + 1);
        for (int i = 1; i <= total_nodes; ++i) {
            cin >> nodes[i].x >> nodes[i].y;
        }

        vector<vector<int>> adj(total_nodes + 1);
        int r2 = r * r;
        for (int i = 1; i <= total_nodes; ++i) {
            for (int j = i + 1; j <= total_nodes; ++j) {
                int dx = nodes[i].x - nodes[j].x;
                int dy = nodes[i].y - nodes[j].y;
                if (dx * dx + dy * dy <= r2) {
                    adj[i].push_back(j);
                    adj[j].push_back(i);
                }
            }
        }

        vector<vector<int>> dist(total_nodes + 1, vector<int>(k + 1, inf));
        queue<pair<int, int>> q;

        dist[1][0] = 0;
        q.push({1, 0});

        while (!q.empty()) {
            auto [u, cost] = q.front();
            q.pop();

            for (int v : adj[u]) {
                int next_cost = cost + (v > n ? 1 : 0);
                
                if (next_cost <= k && dist[v][next_cost] > dist[u][cost] + 1) {
                    dist[v][next_cost] = dist[u][cost] + 1;
                    q.push({v, next_cost});
                }
            }
        }

        int ans = inf;
        for (int j = 0; j <= k; ++j) {
            ans = min(ans, dist[2][j]);
        }

        cout << ans - 1 << "\n";
    };
    // int t;
    // for(cin>>t;t;t--)
    solve();

    return 0;
}

