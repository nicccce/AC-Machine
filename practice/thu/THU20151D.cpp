#include<bits/stdc++.h>
using namespace std;
#define int long long

signed main() {
    ios::sync_with_stdio(0);
    cin.tie(0),cout.tie(0);
    auto solve = [&]() {
        int n,m,k;
        cin>>n>>m>>k;
        vector<vector<pair<int,int>>> g(n+1);
        for(int i=0;i<m;i++){
            int u,v,w;
            cin>>u>>v>>w;
            g[u].push_back({v,w});
            g[v].push_back({u,w});
        }
        auto dfs=[&](int m){
            // cout<<m<<'\n';
            vector<int> vis(n+1);
            for(int i=1;i<=n;i++){
                if(vis[i]==0){
                    int cnt=1;
                    stack<int> st;
                    st.push(i);
                    vis[i]=i;
                    while (!st.empty()){
                        int x=st.top();st.pop();
                        for(auto [nxt,th]:g[x]){
                            if(vis[nxt]==0&&th>=m){
                                st.push(nxt);
                                vis[nxt]=i;
                                cnt++;
                            }
                        }
                    }
                    // if(m==6)cout<<cnt<<'\n';
                    if(cnt>=k)return true;
                }
            }
            return false;
        };
        int l=1, r=1000006; // 初始搜索区间 [l, r]
        int ans = 0;
        while (l <= r) {
            int mid = l + ((r - l) >> 1);
    if (dfs(mid)) {
        ans = mid;
        l = mid + 1; // mid满足，继续向右找
    }
    else {
        r = mid - 1;
    }
        }
        cout<<ans;
    };
    // int t;
    // for(cin>>t;t;t--)
    solve();
    return 0;
}

