#include<bits/stdc++.h>
using namespace std;
#define int long long
const int mod=998244353;
int qpow(int b, int p)
{
    int r = 1;
    while (p)
    {
        if (p & 1)
            r = r * b % mod;
        b = b * b % mod, p >>= 1;
    }
    return r;
}
signed main() {
    ios::sync_with_stdio(0);
    cin.tie(0),cout.tie(0);
    vector<vector<vector<int>>> ways(101,vector<vector<int>>(101));
    auto init=[&]() {
        for (int x = 0; x <= 100; x++) {
            for (int y = 0; x + y <= 100; y++) {
                ways[x][y] = vector<int>(x * y + 1);
                ways[x][y][0] = 1;
                int max_rem = x * y;
                for (int r = 1; r <= max_rem; r++) {
                    long long res = 0;
                    if (y > 0 && r <= x * (y - 1)) res += ways[x][y - 1][r];
                    if (x > 0 && r >= y && r - y <= (x - 1) * y) res += ways[x - 1][y][r - y];
                    ways[x][y][r] = res % mod;
                }
            }
        }   
    };
    init();
    auto solve = [&]() {
        int n, m;
        cin >> n >> m;
        vector<int> p(m), v(m);
        for (int i = 0; i < m; i++) {
            cin >> p[i] >> v[i];
        }

        vector<int> vis(n + 1, -1);
        vis[1] = 0;
        int lstp = 1, lstv = 0;

        vector<int> f(n + 1, 0);
        f[0] = 1;

        for (int i = 0; i < m; i++) {
            if (vis[p[i]] != -1) {
                if (vis[p[i]] != v[i]) {
                    cout << 0 << '\n';
                    return;
                }
                continue;
            }
            vis[p[i]] = v[i];

            int dp = p[i] - lstp;
            int dv = v[i] - lstv;
            if (dv < 0) {
                cout << 0 << '\n';
                return;
            }

            vector<int> nf(n + 1, 0);
            for (int a = 0; a < lstp; a++) {
                if (!f[a]) continue;
                for (int b = a; b <= a + dp; b++) {
                    int x = b - a;
                    int y = dp - x;
                    int rem = dv - a * dp - x * (x + 1) / 2;
                    if (rem >= 0 && rem <= x * y) {
                        nf[b] = (nf[b] + f[a] * ways[x][y][rem]) % mod;
                    }
                }
            }
            f.swap(nf);
            lstp = p[i];
            lstv = v[i];
        }

        int ans = 0;
        for (int b = 0; b <= lstp; b++) {
            ans = (ans + f[b]) % mod;
        }
        ans = ans * qpow(2, n - lstp) % mod;
        cout << ans << '\n';
    };
    int t;
    for(cin>>t;t;t--)
    solve();
    return 0;
}

