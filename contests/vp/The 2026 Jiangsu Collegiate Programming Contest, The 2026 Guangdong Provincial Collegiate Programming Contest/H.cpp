#include<bits/stdc++.h>
using namespace std;
#define int long long
typedef long long ll;
#define lowbit(i) i & (-i)
const int Maxn = 200005;
#define ls (p << 1)
#define rs (p << 1 | 1)

ll a[Maxn], tr[Maxn << 2], lz[Maxn << 2];
bool z[Maxn << 2];

void build(int p, int l, int r) {
    lz[p] = 0;
    z[p] = false;
    if (l == r) {
        tr[p] = a[l];
        return;
    }
    int m = (l + r) >> 1;
    build(ls, l, m);
    build(rs, m + 1, r);
    tr[p] = tr[ls] + tr[rs];
}

// 当前节点对应的区间加v
void apply(int p, int l, int r, ll v) {
    tr[p] += (r - l + 1) * v;
    lz[p] += v;
}

// 当前节点对应的区间置0，旧加法标记作废
void apply0(int p) {
    tr[p] = 0;
    lz[p] = 0;
    z[p] = true;
}

void push(int p, int l, int r) {
    if (l == r) return;
    int m = (l + r) >> 1;

    // 先清零，再加法，顺序不能反
    if (z[p]) {
        apply0(ls);
        apply0(rs);
        z[p] = false;
    }
    if (lz[p]) {
        apply(ls, l, m, lz[p]);
        apply(rs, m + 1, r, lz[p]);
        lz[p] = 0;
    }
}

// [ql, qr]中的每个数加v
void add(int p, int l, int r, int ql, int qr, ll v) {
    if (ql <= l && r <= qr) {
        apply(p, l, r, v);
        return;
    }
    push(p, l, r);
    int m = (l + r) >> 1;
    if (ql <= m) add(ls, l, m, ql, qr, v);
    if (qr > m) add(rs, m + 1, r, ql, qr, v);
    tr[p] = tr[ls] + tr[rs];
}

// [ql, qr]中的每个数置0
void clr(int p, int l, int r, int ql, int qr) {
    if (ql <= l && r <= qr) {
        apply0(p);
        return;
    }
    push(p, l, r);
    int m = (l + r) >> 1;
    if (ql <= m) clr(ls, l, m, ql, qr);
    if (qr > m) clr(rs, m + 1, r, ql, qr);
    tr[p] = tr[ls] + tr[rs];
}

// 查询[ql, qr]的区间和
ll qry(int p, int l, int r, int ql, int qr) {
    if (ql <= l && r <= qr) return tr[p];
    push(p, l, r);
    int m = (l + r) >> 1;
    ll res = 0;
    if (ql <= m) res += qry(ls, l, m, ql, qr);
    if (qr > m) res += qry(rs, m + 1, r, ql, qr);
    return res;
}
int kth(int p,int l,int r,ll v){
    if(l==r) return l;
    push(p,l,r);

    int m=(l+r)>>1;
    if(tr[ls]>=v){
        return kth(ls,l,m,v);
    }
    return kth(rs,m+1,r,v-tr[ls]);
}
signed main() {
    ios::sync_with_stdio(0);
    cin.tie(0),cout.tie(0);
    auto solve = [&]() {
        int n,k;
        cin>>n>>k;
        int silver=0;
        build(1,1,n); 
        priority_queue<pair<int,int>> pq;
        vector<pair<int,int>> ev(n+1);
        for(int i=1;i<=n;i++){
            cin>>ev[i].first>>ev[i].second;
        }
        for(int i=1;i<=n;i++){
            auto [o,x]=ev[i];
            if(o==1){
                add(1,1,n,i,i,x);
            }else if(o==2){
                silver+=x;
            }else{
                int overflow=0;
                if(x%k!=0){
                    if(x%k>silver){
                            while(1){
                                    if(pq.empty()||pq.top().first<=x%k){
                                        overflow=1;
                                        break;
                                    }
                                auto [xx,ii]=pq.top();
                                pq.pop();

                                int tmp=qry(1,1,n,1,ii);
                                if(tmp==0) continue;

                                int ans=kth(1,1,n,tmp);
                                add(1,1,n,ans,ans,-1);

                                silver+=xx-x%k;
                                pq.push({x%k,i});
                                break;
                            }
                    }else{
                        silver-=x%k;
                        pq.push({x%k,i});
                    }
                }
                int need=x/k+overflow;
                int goldcnt=tr[1];

                if(goldcnt<need){
                    silver-=(need-goldcnt)*k;
                    if(silver<0){
                        cout<<-1<<'\n';
                        return;
                    }
                    apply0(1);
                }else if(need>0){
                    int keep=goldcnt-need;

                    if(keep==0){
                        apply0(1);
                    }else{
                        int ans=kth(1,1,n,keep);
                        int tmp=qry(1,1,n,1,ans);
                        if(ans<n){
                            clr(1,1,n,ans+1,n);
                        }
                        add(1,1,n,ans,ans,keep-tmp);
                    }
}
            }
        }
        cout<<silver+qry(1,1,n,1,n)*k<<'\n';
    };
    int t;
    for(cin>>t;t;t--)
    solve();
    return 0;
}

